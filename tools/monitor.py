ACTIVE_BLOCK = r'''
# ---- active: current status+tech on ALL in-scope names, plus a JS-content diff --------------
# Not just the new names. A host whose status / gate / tech CHANGED is the point — a path that
# stopped requiring auth is worth more than a hundred new names. Own snapshots, own baseline,
# own quarantine (a CDN blocklisting the box collapses the probe and must not publish phantoms).
if [ "$ACTIVE" = "1" ]; then
  [ -s "$PENDING" ] || printf '# Unreviewed monitor deltas\n\n> Apex-allowlisted, exclusion-filtered against scope.md. Reconcile each entry; non-domain exclusions cannot be enforced by cron. Read with `tools/monitor.py pending`.\n' > "$PENDING"

  HCUR="$SNAP/$STAMP-http.txt"
  # stderr must attach to httpx (the producer), not to sort; and pipefail alone does not stop a
  # failed probe from becoming a zero-host baseline, so httpx's OWN exit is inspected explicitly.
  httpx -silent -rl "$RATE" __HEADER_FLAGS__ -status-code -tech-detect -no-color < "$CUR" 2>>"$LOG" | sort > "$HCUR"
  HST=${PIPESTATUS[0]}
  HN=$(wc -l < "$HCUR" | tr -d ' ')
  PREVH=$(ls -1 "$SNAP"/*-http.txt 2>/dev/null | grep -v '\.partial' | grep -v "$STAMP" | tail -1)
  if [ "$HST" -ne 0 ] || [ "$HN" -eq 0 ]; then
    mv "$HCUR" "$HCUR.partial" 2>/dev/null
    RUN_FAILED=1
    log "FAIL   httpx exit $HST, $HN host(s) — saved .partial, NOT diffed and NOT a baseline. A failed probe is not a zero-host target."
  elif [ -n "$PREVH" ]; then
    PH=$(wc -l < "$PREVH" | tr -d ' ')
    if [ "$PH" -gt 0 ] && [ "$(( HN * 100 / PH ))" -lt "$MIN_RATIO" ]; then
      mv "$HCUR" "$HCUR.partial"
      RUN_FAILED=1
      log "FAIL   http probe $HN vs previous $PH (< ${MIN_RATIO}%) — saved .partial, NOT diffed (CDN blocklist?)."
    else
      awk 'NR==FNR{k=$1;$1="";p[k]=$0;next}
           {k=$1;$1="";c=$0; if(!(k in p)) print "NEW-LIVE\t"k c;
            else if(p[k]!=c) print "CHANGED\t"k"  was:"p[k]"  now:"c; delete p[k]}
           END{for(k in p) print "GONE-LIVE\t"k p[k]}' "$PREVH" "$HCUR" > /tmp/bbm.$$.hd
      HD=$(wc -l < /tmp/bbm.$$.hd | tr -d ' ')
      if [ "$HD" -gt 0 ]; then
        { echo ""; echo "### http status/tech changes ($STAMP)"; sed 's/^/- /' /tmp/bbm.$$.hd; } >> "$PENDING"
        log "HTTP   $HD status/tech change(s) across $HN live"
      else
        log "HTTP   no status/tech change ($HN live)"
      fi
    fi
  else
    log "INIT   http baseline: $HN live (status+tech). No diff on a first probe."
  fi

  # ---- JS content diff -------------------------------------------------------------------------
  # Hashed bundle FILENAMES rotate every deploy, so they are normalised in the URL KEY only; the
  # BODY is hashed as EXACT bytes (bounded, no normalisation) so a changed key / id / endpoint is
  # NEVER hidden. Discovered URLs are candidates, not approved requests: scheme + in-scope host are
  # validated BEFORE any fetch, and the attribution header is never sent off-scope.
  HGOOD="${HCUR%.partial}"
  grep -F '[200]' "$HGOOD" 2>/dev/null | awk '{print $1}' > /tmp/bbm.$$.live200
  if [ -s /tmp/bbm.$$.live200 ]; then
    if ! command -v katana >/dev/null 2>&1; then
      RUN_FAILED=1
      log "FAIL   katana not on PATH — JS dimension SKIPPED. A missing crawler is not 'no JS change'."
    else
      # -field-scope rdn keeps the crawl inside each seed's own root; output is re-filtered below.
      # katana can exit nonzero after PARTIAL output — that drops URLs and would diff as false
      # JS-GONE — so its exit is inspected and an incomplete crawl is quarantined, not diffed.
      katana -silent -jc -d 2 -field-scope rdn -rl "$RATE" __HEADER_FLAGS__ -list /tmp/bbm.$$.live200 2>>"$LOG" \
        | grep -iE '^https?://' | grep -iE '\.js($|\?)' | sort -u > /tmp/bbm.$$.jsraw
      KST=${PIPESTATUS[0]}
      if [ "$KST" -ne 0 ]; then
        RUN_FAILED=1
        log "FAIL   katana exit $KST — crawl incomplete, URL set untrusted. No JS diff this run (an incomplete crawl is not JS-GONE)."
      else
        # Keep only http/https URLs whose HOST is an in-scope apex AND not excluded. Off-scope refs
        # are recorded as candidates and NEVER fetched — no traffic, no attribution header off-scope.
        EXTF="$SNAP/$STAMP-js-external.txt"; : > "$EXTF"
        awk -v af="$APEXES" -v xf="$EXCLUDES" -v ext="$EXTF" '
          BEGIN{ while((getline a<af)>0) if(a!="")A[a]=1
                 while((getline x<xf)>0) if(x!=""&&substr(x,1,1)!="#")X[x]=1 }
          { url=$0; h=url; sub(/^https?:\/\//,"",h); sub(/^[^@\/]*@/,"",h); sub(/[\/:?#].*$/,"",h); h=tolower(h)
            ok=0
            for(a in A){ s="."a; if(h==a || (length(h)>length(s) && substr(h,length(h)-length(s)+1)==s)){ok=1;break} }
            if(ok){ for(x in X){ s="."x; if(h==x || (length(h)>length(s) && substr(h,length(h)-length(s)+1)==s)){ok=0;break} } }
            if(ok) print url; else print url >> ext }' /tmp/bbm.$$.jsraw > /tmp/bbm.$$.jsurls
        EXTN=$(wc -l < "$EXTF" | tr -d ' ')
        [ "$EXTN" -gt 0 ] && log "JS     $EXTN off-scope JS ref(s) recorded as candidates, NOT fetched"
        JU=$(wc -l < /tmp/bbm.$$.jsurls | tr -d ' ')
        if [ "$JU" -eq 0 ]; then
          RUN_FAILED=1
          log "FAIL   katana found 0 in-scope JS URLs (crawl blocked or all off-scope) — no JS snapshot, no diff. A collapse is not JS-GONE."
        else
          if [ "$JU" -gt __MAXJS__ ]; then
            log "JS     $JU in-scope JS URLs — CAPPING at __MAXJS__ (silent cap; raise --max-js to widen)"
            head -n __MAXJS__ /tmp/bbm.$$.jsurls > /tmp/bbm.$$.jscap && mv /tmp/bbm.$$.jscap /tmp/bbm.$$.jsurls
          fi
          # curl has no request-rate flag, so gate the loop by sleeping 1/RATE after each request
          # (frequency, not bandwidth) — the program rate limit applies to EVERY request path.
          DELAY=$(awk -v r="$RATE" 'BEGIN{if(r<1)r=1; printf "%.4f", 1.0/r}')
          JCUR="$SNAP/$STAMP-js.txt"; : > "$JCUR"
          JFAIL="/tmp/bbm.$$.jsfail"; : > "$JFAIL"
          TMPJS="/tmp/bbm.$$.jsbody"
          FAILED=0
          while IFS= read -r u; do
            key=$(printf '%s' "$u" | sed -E 's/[._-][0-9a-f]{8,}(\.[a-z0-9]+)/\1/g')
            curl -s --proto '=http,https' --max-time 15 --max-filesize 8000000 -o "$TMPJS" __HEADER_FLAGS__ -- "$u" 2>/dev/null
            rc=$?
            sleep "$DELAY"
            # Stream to a BOUNDED file and hash EXACT bytes: a shell var drops NUL bytes and is
            # unbounded, and whitespace-collapsing hides changes inside strings/templates/regex. A
            # key we could not fetch is recorded as FAILED, not silently dropped.
            if [ "$rc" -ne 0 ] || [ ! -s "$TMPJS" ]; then
              FAILED=$((FAILED+1)); printf '%s\n' "$key" >> "$JFAIL"; continue
            fi
            h=$(sha256sum < "$TMPJS" | cut -c1-16)
            printf '%s\t%s\n' "$key" "$h" >> "$JCUR"
          done < /tmp/bbm.$$.jsurls
          rm -f "$TMPJS"
          sort -u -o "$JCUR" "$JCUR"
          sort -u -o "$JFAIL" "$JFAIL"
          JB=$(wc -l < "$JCUR" | tr -d ' ')
          log "JS     attempted $JU · fetched $JB · failed $FAILED"
          PREVJS=$(ls -1 "$SNAP"/*-js.txt 2>/dev/null | grep -v '\.partial' | grep -v "$STAMP" | tail -1)
          if [ "$JB" -eq 0 ]; then
            mv "$JCUR" "$JCUR.partial" 2>/dev/null
            RUN_FAILED=1
            log "FAIL   0 of $JU JS bundles fetched — saved .partial, NOT a baseline and NOT diffed. Zero successful downloads is a failure, not an empty target."
          elif [ -n "$PREVJS" ]; then
            PJ=$(wc -l < "$PREVJS" | tr -d ' ')
            if [ "$PJ" -gt 0 ] && [ "$(( JB * 100 / PJ ))" -lt "$MIN_RATIO" ]; then
              mv "$JCUR" "$JCUR.partial"
              RUN_FAILED=1
              log "FAIL   JS $JB vs previous $PJ (< ${MIN_RATIO}%) — saved .partial, NOT diffed (crawl/fetch collapse is not JS-GONE)."
            else
              SUP=$(comm -12 <(cut -f1 "$PREVJS" | sort -u) "$JFAIL" | wc -l | tr -d ' ')
              # A key we FAILED to fetch is 'unknown', not 'gone' — exclude it from JS-GONE so a
              # single transient download failure never publishes a phantom removal.
              awk -F'\t' -v failf="$JFAIL" '
                BEGIN{ while((getline k < failf)>0) if(k!="") FAIL[k]=1 }
                NR==FNR{p[$1]=$2; next}
                {if(!($1 in p)) print "JS-NEW\t"$1; else if(p[$1]!=$2) print "JS-CHANGED\t"$1; delete p[$1]}
                END{ for(k in p) if(!(k in FAIL)) print "JS-GONE\t"k }' "$PREVJS" "$JCUR" > /tmp/bbm.$$.jd
              JD=$(wc -l < /tmp/bbm.$$.jd | tr -d ' ')
              [ "$SUP" -gt 0 ] && log "JS     $SUP previous key(s) not re-fetched — held back from JS-GONE (fetch failure, not removal)"
              if [ "$JD" -gt 0 ]; then
                { echo ""; echo "### JS content changes — filename-normalised key, exact-body hash ($STAMP)"; sed 's/^/- /' /tmp/bbm.$$.jd; } >> "$PENDING"
                log "JS     $JD JS change(s) across $JB bundles"
              else
                log "JS     no content change ($JB bundles)"
              fi
            fi
          else
            log "INIT   JS baseline: $JB bundles (of $JU, $FAILED failed). No diff on a first crawl."
          fi
        fi
      fi
    fi
  fi
fi
'''


def die(msg, code=2):
    print(f"FAIL — {msg}", file=sys.stderr)
    raise SystemExit(code)


def ssh_prefix():
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "config.py"), "ssh"],
                       capture_output=True, text=True)
    if r.returncode != 0 or not r.stdout.strip():
        die("no VPS configured (tools/config.py ssh). Scheduled monitoring needs one.")
    return shlex.split(r.stdout.strip())


def remote(cmd, check=True, stdin=None):
    r = subprocess.run(ssh_prefix() + [cmd], capture_output=True, text=True, input=stdin)
    if check and r.returncode != 0:
        die(f"remote command failed: {cmd}\n       {r.stderr.strip()}")
    return r


def target_of(arg):
    p = Path(arg).resolve()
    if not p.is_dir() or not (p / "index.md").exists():
        die(f"{arg} is not a target brain (no index.md)")
    return p


# Two-label public suffixes, so `acme.com.tw` collapses to itself and not to `com.tw`.
# A pragmatic list, not the Public Suffix List — enough for program scopes, and wrong only in
# the direction of keeping a longer name, which is the safe direction.
def derive_apexes(tdir, verbose=True):
    """Authorised enumeration roots from scope.md — never a widened guess.

    A wildcard entry is an enumeration root; an exact host is **not**. Enumerating `acme.com`
    because `app.acme.com` is in scope would authorise the whole estate from one host, so exact
    entries are reported as skipped rather than silently promoted.
    """
    s = parse_scope(tdir)
    roots, skipped = enumeration_roots(s)
    derive_apexes.last_exclusions = sorted({d for _, d in s["out_of_scope"]})
    derive_apexes.last_prose = s["prose"]
    derive_apexes.last_state = s["state"]
    derive_apexes.last_detail = s["detail"]
    derive_apexes.last_skipped = skipped
    derive_apexes.last_parsed = s
    if verbose:
        if derive_apexes.last_exclusions:
            print(f"  excluded    {', '.join(derive_apexes.last_exclusions)} (from scope.md)")
        for dom, why in skipped:
            print(f"  not a root  {dom} — {why}")
    return roots


def cron_line(target, script, every, minute):
    hours = f"*/{every}" if every < 24 else "0"
    return f"{minute} {hours} * * * {script}  # {MARKER}:{target}"


def read_crontab():
    return remote("crontab -l 2>/dev/null || true", check=False).stdout


def write_crontab(text):
    if not text.endswith("\n"):
        text += "\n"
    r = subprocess.run(ssh_prefix() + ["crontab -"], input=text, capture_output=True, text=True)
    if r.returncode != 0:
        die(f"could not install crontab: {r.stderr.strip()}")


def strip_marker(text, target):
    tag = f"# {MARKER}:{target}"
    return "\n".join(l for l in text.splitlines() if tag not in l)


# ---------------------------------------------------------------- commands

def cmd_enable(args):
    tdir = target_of(args.target)
    name = tdir.name
    if not (1 <= args.every <= 24):
        die("--every must be between 1 and 24 hours")
    if not (1 <= args.min_ratio <= 100):
        die("--min-ratio is a percent of the previous snapshot — it must be between 1 and 100")
    if args.keep_days < 1:
        die("--keep-days must be at least 1")
    if args.max_js < 1:
        die("--max-js must be a positive count of bundles")
    if args.active and args.rate is None:
        die("--active needs --rate: an unattended prober must carry the program's rate limit")
    if args.rate is not None and not (1 <= args.rate <= 1000):
        die("--rate must be between 1 and 1000 req/s — 0 or negative is not a rate, and >1000 is not a courtesy")
    if args.active and not args.header:
        print("  note: --active with no --header. If the program mandates an attribution header,\n"
              "        every request this job makes will be non-compliant.", file=sys.stderr)

    if args.apex:
        derive_apexes(tdir, verbose=False)              # populate exclusions + the parse
        parsed = getattr(derive_apexes, "last_parsed", {"in_scope": [], "out_of_scope": []})
        unauthorised = [a for a in args.apex if not authorises(a, parsed)]
        if unauthorised:
            die("--apex must be covered by scope.md; these are not: "
                + ", ".join(unauthorised)
                + "\n       An explicit root is a convenience, not an authorisation. Add it to "
                  "the\n       mechanical allowlist first if the program really covers it.")
        apexes = [a.lower() for a in args.apex]
    else:
        apexes = derive_apexes(tdir)
    if not apexes:
        die(getattr(derive_apexes, "last_detail", "") or
            f"no in-scope domains in {name}/scope.md — pass --apex explicitly")
    excludes = list(getattr(derive_apexes, "last_exclusions", []))
    prose = list(getattr(derive_apexes, "last_prose", []))

    # An exclusion the job cannot express is the whole active-probing risk: a wildcard apex would
    # otherwise authorise probing a host the program explicitly carved out.
    if prose and args.active and not args.ack_prose_exclusions:
        print(f"\nFAIL — {len(prose)} out-of-scope entr(y/ies) in scope.md are not domain-shaped, "
              f"so the job\n       cannot enforce them:", file=sys.stderr)
        for s in prose[:6]:
            print(f"         {s}", file=sys.stderr)
        print("\n       Active probing would hit anything matching an in-scope apex regardless.",
              file=sys.stderr)
        print("       Either add the concrete hostnames to scope.md's out-of-scope section, run",
              file=sys.stderr)
        print("       without --active, or pass --ack-prose-exclusions to accept the gap.",
              file=sys.stderr)
        return 2

    script = f"$HOME/targets/{name}/jobs/monitor.sh"
    minute = int(hashlib.sha256(name.encode()).hexdigest(), 16) % 60   # stagger targets
    line = cron_line(name, script, args.every, minute)
    hflags = " ".join(f"-H {shlex.quote(h)}" for h in (args.header or []))

    print(f"\n  target      {name}")
    print(f"  apexes      {', '.join(apexes)}")
    print(f"  excluded    {', '.join(excludes) if excludes else 'none domain-shaped in scope.md'}")
    if prose:
        print(f"  ⚠ prose     {len(prose)} exclusion(s) the job cannot enforce "
              f"(non-domain): {prose[0][:60]}…")
    if not args.apex:
        print("              (derived from scope.md — check them; a wrong apex means a wrong filter)")
    print(f"  schedule    every {args.every}h at minute {minute}")
    print(f"  script      {script}")
    if args.active:
        print(f"  probing     {args.rate} req/s · {len(args.header or [])} header(s):")
        print(f"                · status + tech on ALL in-scope names (diffs CHANGES, not just new)")
        print(f"                · JS-content diff on live 200s, hash-normalised (≤ {args.max_js} bundles/run)")
    else:
        print("  probing     off — passive name enumeration only (--active adds status/tech + JS diff)")
    print(f"  snapshots   immutable, dated; diffed against the previous good one; kept {args.keep_days}d")
    print(f"  guard       a run under {args.min_ratio}% of the previous is saved .partial and NOT diffed\n")

    if not args.yes:
        print("  re-run with --yes to install this")
        return 1

    remote(f"mkdir -p ~/targets/{name}/jobs ~/targets/{name}/logs ~/targets/{name}/raw/snapshots")
    remote(f"cat > ~/targets/{name}/monitor-apexes.txt", stdin="\n".join(apexes) + "\n")
    remote(f"cat > ~/targets/{name}/monitor-excludes.txt",
           stdin=("# generated from scope.md out-of-scope section\n"
                  + "\n".join(excludes) + ("\n" if excludes else "")))

    # The job runs on the VPS where config.json does not exist. When notification channels are
    # configured locally, push a standalone copy (webhook URLs are credentials: chmod 600) so the
    # cron job can ping on deltas, quarantines and failures. No channels -> the job's
    # notify_event() stays a silent no-op.
    import json as _json
    import config as _config
    _flat = _config.load()
    _channels = _flat.get("notify.channels") or []
    if _channels:
        codedir = _flat.get("vps.codedir", "~/hunterstick")
        remote(f"mkdir -p {codedir}/tools")
        remote(f"cat > {codedir}/notify.json",
               stdin=_json.dumps({"channels": _channels,
                                  "strict": bool(_flat.get("notify.strict"))}) + "\n")
        remote(f"chmod 600 {codedir}/notify.json")
        print(f"  notify       {len(_channels)} channel(s) — deltas, quarantines and failures ping it")
    else:
        print("  notify       off — set notify.channels in config.json to be pinged on deltas")

    active_block = (ACTIVE_BLOCK.replace("__HEADER_FLAGS__", hflags)
                                .replace("__MAXJS__", str(args.max_js)))
    body = REMOTE_SCRIPT.format(marker=MARKER, target=name, min_ratio=args.min_ratio,
                                keep_days=args.keep_days, active=1 if args.active else 0,
                                rate=args.rate or 0, active_block=active_block,
                                codedir=_config.load().get("vps.codedir", "~/hunterstick"))
    remote(f"cat > {script}", stdin=body)
    remote(f"chmod +x {script}")

    # httpx AND katana are both required for --active: without katana the JS dimension the skill
    # promises would silently never run, and a silent gap reads as "no JS change".
    need = ["subfinder", "flock"] + (["httpx", "katana"] if args.active else [])
    for tool in need:
        if remote(f"command -v {tool} >/dev/null && echo yes || echo no",
                  check=False).stdout.strip() != "yes":
            die(f"{tool} is not on the VPS PATH — the job would fail every {args.every}h, silently")
    if remote(f"bash -n {script} && echo ok || echo bad", check=False).stdout.strip() != "ok":
        die("the generated script does not parse on the VPS — nothing scheduled")

    write_crontab((strip_marker(read_crontab(), name) + "\n" + line).strip())
    if line not in read_crontab():
        die("crontab did not come back with the entry — nothing is scheduled")

    print(f"  installed   {line}")
    print("\n  The first run writes a baseline and reports no delta — correct, not a bug.")
    print(f"  Check it:   tools/monitor.py status {args.target}")
    return 0


def cmd_disable(args):
    name = target_of(args.target).name
    cur = read_crontab()
    if f"{MARKER}:{name}" not in cur:
        print(f"  nothing scheduled for {name}")
        return 1
    write_crontab(strip_marker(cur, name))
    print(f"  removed the schedule for {name}. Script, snapshots and log are untouched.")
    return 0


def cmd_status(args):
    name = target_of(args.target).name
    entry = [l for l in read_crontab().splitlines() if f"{MARKER}:{name}" in l]
    print(f"\n# monitor — {name}")
    print(f"  schedule    {entry[0].strip() if entry else 'NOT SCHEDULED'}")

    q = (f"T=$HOME/targets/{name}; S=$T/raw/snapshots; "
         f"echo GOOD=$(ls -1 $S/*-subdomains.txt 2>/dev/null | grep -vc '\\.partial' || echo 0); "
         f"echo PART=$(ls -1 $S/*.partial 2>/dev/null | wc -l); "
         f"echo LAST=$(ls -1 $S/*-subdomains.txt 2>/dev/null | grep -v '\\.partial' | tail -1); "
         f"echo NAMES=$(ls -1 $S/*-subdomains.txt 2>/dev/null | grep -v '\\.partial' | tail -1 "
         f"| xargs -r wc -l | awk '{{print $1}}'); "
         f"echo PEND=$(grep -c '^## ' $T/monitor-pending.md 2>/dev/null || echo 0); "
         f"echo '--- log ---'; tail -8 $T/logs/monitor.log 2>/dev/null")
    out = remote(q, check=False).stdout

    def g(k, d="?"):
        m = re.search(rf"{k}=(\S*)", out)
        return m.group(1) if m and m.group(1) else d

    print(f"  snapshots   {g('GOOD','0')} good · {g('PART','0')} quarantined (.partial)")
    print(f"  latest      {Path(g('LAST','—')).name}  ({g('NAMES','?')} names)")
    print(f"  pending     {g('PEND','0')} unreviewed delta block(s)")
    tail = out.split("--- log ---", 1)
    if len(tail) == 2 and tail[1].strip():
        print("\n  log:")
        for l in tail[1].strip().splitlines():
            print(f"    {l}")
        if "FAIL" in tail[1]:
            print("\n  ⚠ FAIL above: a run was quarantined and NOT diffed. Read it — a monitor")
            print("    failing quietly is worse than no monitor.")
    else:
        print("\n  log:        empty — the job has not run yet")
    print()
    return 0


def cmd_pending(args):
    name = target_of(args.target).name
    out = remote(f"cat $HOME/targets/{name}/monitor-pending.md 2>/dev/null", check=False).stdout
    if not out.strip():
        print(f"  no pending delta for {name}")
        return 0
    print(out.rstrip())
    print("\n  Reconcile each against scope.md, then score into attack-surface.md "
          "(the `attack-surface-prioritization` model).")
    if args.clear:
        remote(f"rm -f $HOME/targets/{name}/monitor-pending.md")
        print("  cleared — only correct once the names are recorded in the brain.")
    return 0


def cmd_run(args):
    name = target_of(args.target).name
    script = f"$HOME/targets/{name}/jobs/monitor.sh"
    if remote(f"test -x {script} && echo yes || echo no", check=False).stdout.strip() != "yes":
        die(f"no monitor script for {name} — run enable first")
    print(f"  running one pass for {name} … (may take several minutes)")
    # Capture the REAL remote exit code. A trailing `echo` would make ssh return 0 and turn a failed
    # run into a false success (and a false 'ok' in the run ledger) — the exact fail-loud violation
    # this tool exists to prevent. Marker-parse the script's own status instead.
    r = remote(f"{script}; echo __MONRC=$?", check=False)
    m = re.search(r"__MONRC=(\d+)", r.stdout)
    rc = int(m.group(1)) if m else 1        # no marker => ssh transport failed => not a success
    disp = re.sub(r"\n?__MONRC=\d+\s*$", "", r.stdout).strip()
    print("  " + (disp or "(no stdout; see the remote log)").replace("\n", "\n  "))
    cmd_status(args)                         # diagnostics either way
    if rc != 0:
        print(f"\n  FAIL — the monitor run exited {rc}. Nothing from a failed run is trusted; the\n"
              f"         snapshot (if any) was quarantined. Check the log before the next interval.",
              file=sys.stderr)
    return rc


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("enable", help="install the cron job")
    e.add_argument("target")
    e.add_argument("--every", type=int, default=12, metavar="H", help="hours between runs (default 12)")
    e.add_argument("--apex", action="append", help="apex to enumerate; repeatable. Omit to derive from scope.md")
    e.add_argument("--active", action="store_true",
                   help="each run: status+tech on ALL in-scope names (changes, not just new) + a JS-content diff")
    e.add_argument("--rate", type=int, metavar="RPS", help="req/s cap for --active (required with it)")
    e.add_argument("--header", action="append", metavar="H", help="header sent on every probe; repeatable")
    e.add_argument("--max-js", type=int, default=800, metavar="N",
                   help="max JS bundles to fetch+hash per run for the content diff (default 800)")
    e.add_argument("--min-ratio", type=int, default=50, metavar="PCT",
                   help="quarantine a run under PCT%% of the previous snapshot (default 50)")
    e.add_argument("--keep-days", type=int, default=30, help="snapshot retention (default 30)")
    e.add_argument("--ack-prose-exclusions", action="store_true",
                   help="accept that non-domain exclusions in scope.md cannot be enforced")
    e.add_argument("--yes", action="store_true", help="actually install it")
    e.set_defaults(fn=cmd_enable)

    for nm, fn, hlp in (("status", cmd_status, "schedule, snapshots, pending count, recent log"),
                        ("disable", cmd_disable, "remove the schedule; keep all data"),
                        ("run", cmd_run, "run one pass now")):
        p = sub.add_parser(nm, help=hlp)
        p.add_argument("target")
        p.set_defaults(fn=fn)

    p = sub.add_parser("pending", help="show unreviewed deltas")
    p.add_argument("target")
    p.add_argument("--clear", action="store_true", help="clear after recording them in the brain")
    p.set_defaults(fn=cmd_pending)

    args = ap.parse_args()
    return args.fn(args)


