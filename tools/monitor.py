#!/usr/bin/env python3
"""Scheduled recon monitoring — install, inspect and remove a VPS cron job.

    tools/monitor.py enable  targets/acme --every 12 \
                             --active --rate 45 --header 'X-Bug-Bounty: <your-handle>' --yes
    tools/monitor.py status  targets/acme
    tools/monitor.py pending targets/acme [--clear]
    tools/monitor.py run     targets/acme        # one pass now, the same script cron runs
    tools/monitor.py disable targets/acme        # removes the schedule, keeps every file

`monitoring-and-diff` is a diff *pass* a human invokes. This is the part that legitimately runs
unattended:
enumerate on an interval, diff consecutive snapshots, hold the delta for the next session. With
`--active` it monitors three dimensions, each with its own immutable snapshot and quarantine:
  * **new/removed subdomain names** (subfinder);
  * **status + tech on ALL in-scope names** — so a host that CHANGED (a gate that appeared or
    vanished, a tech that shifted) is caught, not just brand-new names;
  * **JS content** on the live 200s — diffed by hash after normalising away content-hashed
    filenames, so a real bundle change surfaces without one-alert-per-deploy noise.

Design rules, in order of importance:

  1. NOTHING IS EVER OVERWRITTEN. Every run writes its own dated snapshot and diffs it against the
     previous one. Snapshots are immutable. There is no rolling baseline to corrupt, deletions are
     visible (a rolling `anew` baseline can only ever show additions), and any past run can be
     re-diffed later.
  2. A PARTIAL RUN IS QUARANTINED, NOT COMPARED. Expired API keys returning 200 names instead of
     55,200 would produce 55,000 phantom deletions and then 55,000 phantom additions next run. A run
     under --min-ratio of the previous snapshot is saved with a `.partial` suffix, excluded from
     future comparisons, and logged FAIL. The data is kept; the false delta is not published.
  3. THE FIRST RUN IS A BASELINE, NOT A DELTA. It says so in the log and reports nothing.
  4. PROGRAM POLICY IS ENCODED IN THE JOB. `--active` probing carries the rate limit and the
     attribution header on every request, because that is what the program requires — not because
     of the hour it runs at. `--active` without `--rate` is refused.

Scope: the job filters to an allowlist AND an exclusion list, both generated from scope.md at
enable time. A host that matches an in-scope apex but also matches an exclusion is dropped before
it is recorded and before anything probes it. Exclusions that are not domain-shaped ("Flickr",
"divested brands") cannot be enforced mechanically — `enable` prints them and refuses `--active`
until you acknowledge with --ack-prose-exclusions, because a wildcard apex would otherwise
authorise probing a host the program explicitly carved out.

Exit: 0 ok · 1 refused (needs --yes, or nothing to do) · 2 failed.
"""
